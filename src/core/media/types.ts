/**
 * dsh-canvas — 媒体生成的公共词汇（F2.7）。
 *
 * 三种能力、以及它们在**纯逻辑与 host 之间的那条边界**上用什么形状传递。这个文件
 * 刻意只放类型：`core/` 不许 import 到 host，而 host 与 core 两边都要说「图片 / 视频 /
 * 音频」，所以这组词必须住在一个两边都拿得动的地方。
 */

/**
 * 一种媒体生成能力。
 *
 * 与 kind 的关系是**刻意不等的**：kind 说的是产物**是什么形态**（`image` / `video` /
 * `audio`，由文件证据判定），这里是**要生成哪一种**。今天它们一一对应，明天不会——
 * 一张图片可以由「图生视频」这条线产出（产物是视频），而那时 kind 表一个字都不用改。
 * 所以两边不互相推导，各自是真源。
 */
export type MediaCapability = 'image' | 'video' | 'audio'
